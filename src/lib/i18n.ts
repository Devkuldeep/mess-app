export const dictionaries = { en: en as Dict, hi };
export type Lang = keyof typeof dictionaries;
export const LANG_COOKIE = "lang";
export const DEFAULT_LANG: Lang = "hi";

export function isLang(v: unknown): v is Lang {
  return v === "en" || v === "hi";
}

export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

export function formatHour(h: number, lang: Lang): string {
  const d = new Date(Date.UTC(2000, 0, 1, h));
  return new Intl.DateTimeFormat(lang === "hi" ? "hi-IN" : "en-IN", { hour: "numeric", timeZone: "UTC" }).format(d);
}

export function formatDate(iso: string, lang: Lang, opts: Intl.DateTimeFormatOptions = { weekday: "short", day: "numeric", month: "short" }): string {
  return new Intl.DateTimeFormat(lang === "hi" ? "hi-IN" : "en-IN", { ...opts, timeZone: "UTC" }).format(new Date(`${iso}T00:00:00Z`));
}

export function formatMoney(n: number): string {
  return `₹${new Intl.NumberFormat("en-IN", { maximumFractionDigits: 2 }).format(n)}`;
}
